// One-time devnet setup for the hosted app.
//   node scripts/setup.mjs keygen  -> creates the relayer key outside the repo, prints its address only
//   node scripts/setup.mjs init    -> demo stablecoin mint, relayer treasury, foundation match pool; writes lib/config.js
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Connection, Keypair, Transaction, sendAndConfirmTransaction } from "@solana/web3.js";
import { createMint, getOrCreateAssociatedTokenAccount, mintTo } from "@solana/spl-token";
import * as dala from "../lib/dala.js";

const KEY_PATH = process.env.RELAYER_KEYPAIR || path.join(os.homedir(), ".config", "dala", "relayer-devnet.json");
const here = path.dirname(fileURLToPath(import.meta.url));
const conn = new Connection(process.env.RPC_URL || "https://api.devnet.solana.com", "confirmed");
const PERIOD_SECS = 30;

function keygen() {
  if (fs.existsSync(KEY_PATH)) {
    console.log("relayer exists:", load().publicKey.toBase58());
    return;
  }
  fs.mkdirSync(path.dirname(KEY_PATH), { recursive: true });
  const kp = Keypair.generate();
  fs.writeFileSync(KEY_PATH, JSON.stringify(Array.from(kp.secretKey)), { mode: 0o600 });
  console.log("relayer created:", kp.publicKey.toBase58());
}

function load() {
  return Keypair.fromSecretKey(Uint8Array.from(JSON.parse(fs.readFileSync(KEY_PATH, "utf8"))));
}

async function init() {
  const r = load();
  console.log("relayer", r.publicKey.toBase58(), "balance", (await conn.getBalance(r.publicKey)) / 1e9, "SOL");
  const mint = await createMint(conn, r, r.publicKey, null, 6);
  const treasury = await getOrCreateAssociatedTokenAccount(conn, r, mint, r.publicKey);
  await mintTo(conn, r, mint, treasury.address, r, 50_000_000 * dala.USDC);

  const pool = dala.poolPda(r.publicKey, mint);
  const tx = new Transaction().add(
    dala.createMatchPool({ sponsor: r.publicKey, mint, matchBps: 10_000, capPerWorker: 100 * dala.USDC }),
    dala.fundPool({ funder: r.publicKey, from: treasury.address, mint, pool, amount: 1_000_000 * dala.USDC }),
  );
  const sig = await sendAndConfirmTransaction(conn, tx, [r], { commitment: "confirmed" });
  console.log("pool created and funded:", sig);

  const config = {
    relayer: r.publicKey.toBase58(),
    mint: mint.toBase58(),
    pool: pool.toBase58(),
    periodSecs: PERIOD_SECS,
  };
  const out = `// Generated by scripts/setup.mjs. Public addresses only.\nexport const CONFIG = ${JSON.stringify(config, null, 2)};\n`;
  fs.writeFileSync(path.join(here, "..", "lib", "config.js"), out);
  console.log("wrote lib/config.js", config);
}

const cmd = process.argv[2];
if (cmd === "keygen") keygen();
else if (cmd === "init") init().catch((e) => { console.error(e); process.exit(1); });
else console.log("usage: node scripts/setup.mjs keygen|init");
